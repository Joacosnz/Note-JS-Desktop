const assert = require('node:assert/strict');
const fs = require('node:fs'), os = require('node:os'), path = require('node:path');
const {spawn} = require('node:child_process');
const {openBrowser,until} = require('./browser_helpers.cjs');
const root = path.resolve(__dirname,'..');
const temporary = fs.mkdtempSync(path.join(os.tmpdir(),'notejs-covers-'));
const python = process.env.NOTEJS_TEST_PYTHON || path.join(process.env.LOCALAPPDATA,'Python/pythoncore-3.15-64/python.exe');
let server,browser;
async function startServer() {
  server = spawn(python,['-u',path.join(__dirname,'cover_photo_test_server.py'),temporary],{cwd:root,windowsHide:true});
  server.stderr.on('data',data=>process.stderr.write(data));
  const port = await new Promise((resolve,reject)=>{server.stdout.once('data',data=>resolve(Number(data.toString().trim())));server.once('error',reject);});
  return `http://127.0.0.1:${port}`;
}
(async()=>{
  let origin = await startServer();
  browser = await openBrowser(temporary);
  const evaluate = browser.evaluate;
  await browser.navigate(origin);
  await until(()=>evaluate('!!window.NoteJSLocal'),'App did not initialize');
  await evaluate('window.NoteJSLocal.ready');
  await evaluate(`(async()=>{await NoteJSLocal.persist({id:987654321,title:'Portada de prueba',folder:'Pruebas',content:'Texto que no debe verse en la tarjeta',tags:'etiqueta-oculta',hasCover:false});loadNote(987654321)})()`);
  const original = path.join(temporary,'foto-original.png');
  const data = await evaluate(`(()=>{const c=document.createElement('canvas');c.width=1200;c.height=800;const x=c.getContext('2d');const g=x.createLinearGradient(0,0,1200,800);g.addColorStop(0,'#176f89');g.addColorStop(1,'#eead6c');x.fillStyle=g;x.fillRect(0,0,1200,800);return c.toDataURL('image/png').split(',')[1]})()`);
  fs.writeFileSync(original,Buffer.from(data,'base64'));
  await evaluate('toggleCover()');
  const doc=await browser.call('DOM.getDocument',{},browser.sessionId);
  const {nodeId}=await browser.call('DOM.querySelector',{nodeId:doc.root.nodeId,selector:'#cover-photo-picker'},browser.sessionId);
  await browser.call('DOM.setFileInputFiles',{nodeId,files:[original]},browser.sessionId);
  await until(()=>evaluate("/^url\\(\\/api\\/covers\\//.test(getActiveNote()?.coverStyle || '')"),'Gallery photo was not imported');
  const style = await evaluate('getActiveNote().coverStyle');
  const url = style.slice(4,-1);
  fs.unlinkSync(original);
  assert.equal((await fetch(origin+url)).headers.get('content-type'),'image/jpeg');
  assert.ok(await evaluate(`(async()=>{const image=new Image();image.src=${JSON.stringify(url)};await image.decode();return image.naturalWidth===1200&&image.naturalHeight===800})()`));
  assert.ok((await evaluate("getComputedStyle(document.getElementById('notion-cover')).backgroundImage")).includes('/api/covers/'));
  assert.equal(await evaluate("document.querySelector('#btn-reposition-cover, #cover-reposition-bar')"),null);
  await evaluate("navigateToHome();setHomeNotesView('grid')");
  const grid = await evaluate(`(()=>{const c=document.querySelector('[data-home-note-id="987654321"]');return {text:c.textContent.trim(),photo:getComputedStyle(c.querySelector('.home-grid-card-cover')).backgroundImage,children:c.children.length}})()`);
  assert.equal(grid.text,'Portada de prueba');
  assert.equal(grid.children,2);
  assert.ok(grid.photo.includes('/api/covers/'));
  const screenshot=await browser.call('Page.captureScreenshot',{format:'png'},browser.sessionId);
  fs.mkdirSync(path.join(root,'.test-artifacts'),{recursive:true});
  fs.writeFileSync(path.join(root,'.test-artifacts','desktop-photo-grid.png'),Buffer.from(screenshot.data,'base64'));
  const bad = await evaluate(`(async()=>{try{await importNoteCoverPhoto(new File(['texto'],'falsa.png',{type:'image/png'}),987654321);return 'accepted'}catch{return 'rejected'}})()`);
  assert.equal(bad,'rejected');
  assert.equal(await evaluate('state.notes.find(n=>n.id===987654321).coverStyle'),style);
  assert.equal((await fetch(origin+'/api/covers',{method:'POST',headers:{'Content-Type':'image/jpeg'},body:'invalid'})).status,400);
  assert.equal((await fetch(origin+'/api/covers',{method:'POST',headers:{'Content-Type':'image/jpeg',Origin:'https://example.com'},body:'invalid'})).status,403);
  assert.equal((await fetch(origin+'/api/covers/'+'a'.repeat(64)+'.jpg')).status,404);
  // A new process/port must resolve the same private file and database reference.
  server.kill();
  origin = await startServer();
  await browser.navigate(origin);
  await until(()=>evaluate('!!window.NoteJSLocal'),'App did not restart');
  await evaluate('window.NoteJSLocal.ready');
  assert.equal(await evaluate('state.notes.find(n=>n.id===987654321).coverStyle'),style);
  assert.equal((await fetch(origin+url)).status,200);
  await evaluate('loadNote(987654321);toggleCover()');
  await until(async()=>{const b=await fetch(origin+'/api/bootstrap').then(r=>r.json());return b.notes.find(n=>n.id===987654321)?.hasCover===false;},'Removing the photo did not persist');
  await evaluate("navigateToHome();setHomeNotesView('grid')");
  const uncovered=await evaluate(`(()=>{const c=document.querySelector('[data-home-note-id="987654321"]');return {photo:!!c.querySelector('.home-grid-card-cover'),text:c.querySelector('.home-grid-card-content-preview')?.textContent}})()`);
  assert.equal(uncovered.photo,false);
  assert.equal(uncovered.text,'Texto que no debe verse en la tarjeta');
  console.log('Cover photo E2E passed: gallery import, durable file, grid, no reposition button, invalid files, restart and removal.');
})().catch(error=>{console.error(error);process.exitCode=1;}).finally(async()=>{if(browser)await browser.close();if(server)server.kill();});
